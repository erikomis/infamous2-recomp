#!/usr/bin/env python3
"""lift_datamods.py EBOOT.elf [--out spu] [--lsa 0x6C00] [--first-image-id 230]

The WWS job manager's second kind of module. Beside the C0DEC0DE job code
modules (tools/extract_eboot_jobmods.py), inFAMOUS 2's EBOOT carries five
blobs tagged DA7ABA5E, same layout (4 x ila, magic, code offset 0x30, size),
that one job streams into a second local-store buffer at LS 0x6C00 and
calls. Nothing lifted them, so every such call ran on the interpreter --
22,000 instructions at a time in the main menu.

Each blob is wrapped as an SPU ELF at --lsa, lifted with the toolkit's SPU
lifter (prefix datamod_<ea>_) into <out>/datamod_<ea>/, and
<out>/datamods_register.c registers the lift as a code region at the blob's
guest address, so the GET that loads it makes the lift resident.
"""
import argparse, os, re, struct, subprocess, sys

here = os.path.dirname(os.path.abspath(__file__))
toolkit = os.environ.get('PS3RECOMP', os.path.join(here, '..', '..', 'ps3recomp-fork'))
sys.path.insert(0, os.path.join(toolkit, 'tools'))
import lift_jobmods as lj   # noqa: E402  (wrap, manual_link_targets, switch_table_targets)

MAGIC = b'\xDA\x7A\xBA\x5E'
INC_RE = re.compile(r'#include "(?:\.\./)+runtime/spu/')


def find_blobs(d):
    out, i = [], 0
    while True:
        i = d.find(MAGIC, i + 1)
        if i < 0:
            return out
        s = i - 0x10
        if i % 4 or s < 0:
            continue
        if not all((struct.unpack_from('>I', d, s + 4 * k)[0] >> 24) in (0x42, 0x43) for k in range(4)):
            continue
        code_off, size = struct.unpack_from('>II', d, i + 4)
        code_end = struct.unpack_from('>I', d, i + 0x10)[0]
        out.append((s, code_off, size, code_end))


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument('eboot')
    ap.add_argument('--out', default=os.path.join(here, '..', 'spu'))
    ap.add_argument('--lsa', type=lambda x: int(x, 0), default=0x6C00)
    ap.add_argument('--first-image-id', type=int, default=230)
    ap.add_argument('--va-offset', type=lambda x: int(x, 0), default=0x10000,
                    help='guest address = file offset + this (the first PT_LOAD)')
    ap.add_argument('--extra', default='',
                    help='comma-separated LS addresses to add as entries in every blob that '
                         'spans them (interrupt-resume points seen in [rejoin] lines)')
    a = ap.parse_args()

    d = open(a.eboot, 'rb').read()
    blobs = find_blobs(d)
    if not blobs:
        sys.exit('no DA7ABA5E blobs found')
    regs = []
    for n, (s, code_off, size, code_end) in enumerate(blobs):
        ea = s + a.va_offset
        raw = d[s:s + size]
        name = f'datamod_{ea:08x}'
        prefix = name + '_'
        outsub = os.path.join(a.out, name)
        os.makedirs(outsub, exist_ok=True)
        tmp = os.path.join(a.out, f'_tmp_{name}.elf')
        with open(tmp, 'wb') as f:
            f.write(lj.wrap(raw, base=a.lsa, entry=a.lsa + code_off))
        extras = {hex(a.lsa + code_off)}
        extras |= {hex(x) for x in lj.manual_link_targets(raw, base=a.lsa)}
        extras |= {hex(x) for x in lj.switch_table_targets(raw, base=a.lsa)}
        for x in a.extra.split(','):
            if x.strip() and a.lsa + code_off <= int(x, 0) < a.lsa + code_end:
                extras.add(hex(int(x, 0)))
        cmd = [sys.executable, os.path.join(toolkit, 'tools', 'spu_lifter.py'), '--auto-functions', tmp,
               '--base', hex(a.lsa), '--symbol-prefix', prefix, '-o', outsub,
               '--source-name', 'spu_recomp.c', '--header-name', 'spu_recomp.h',
               '--code-end', hex(a.lsa + code_end), '--extra-funcs', ','.join(sorted(extras))]
        r = subprocess.run(cmd, capture_output=True, text=True)
        os.remove(tmp)
        if r.returncode != 0:
            sys.exit(f'{name}: lift failed\n{r.stderr}')
        for fn in ('spu_recomp.c', 'spu_recomp.h'):
            p = os.path.join(outsub, fn)
            t = open(p).read()
            open(p, 'w').write(INC_RE.sub('#include "', t))
        funcs = next((l.strip() for l in r.stdout.splitlines() if l.strip().endswith('function(s) lifted')), '?')
        img = a.first_image_id + n
        print(f'  {name}: file+0x{s:X} size 0x{size:X} code 0x{code_off:X}..0x{code_end:X} -> LS 0x{a.lsa:X}, image {img}, {funcs}')
        regs.append((name, prefix, ea, size, img))

    reg = os.path.join(a.out, 'datamods_register.c')
    L = ['/* datamods_register.c -- GENERATED by tools/lift_datamods.py.',
         ' * The DA7ABA5E modules the WWS job manager streams to LS 0x%X, registered as' % a.lsa,
         ' * code regions at their guest addresses so the GET that loads one makes its',
         ' * lift resident (spu_overlay_register_region_at). */',
         '#include <stdint.h>', '',
         'extern void spu_begin_image(int image_id);',
         'extern void spu_overlay_register_region_at(uint32_t content_ea, uint32_t lsa, uint32_t span, int image_id);']
    L += [f'extern void {p}spu_recomp_register(void);' for _, p, _, _, _ in regs]
    L += ['', '__attribute__((constructor)) static void infamous2_datamods_register(void)', '{']
    for name, p, ea, size, img in regs:
        L.append(f'    spu_begin_image({img}); {p}spu_recomp_register();')
        L.append(f'    spu_overlay_register_region_at(0x{ea:08X}u, 0x{a.lsa:X}u, 0x{size:X}u, {img});   /* {name} */')
    L += ['    spu_begin_image(0);', '}', '']
    open(reg, 'w').write('\n'.join(L))
    print(f'wrote {reg} ({len(regs)} modules)')


if __name__ == '__main__':
    main()
