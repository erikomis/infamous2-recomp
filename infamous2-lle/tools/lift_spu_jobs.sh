#!/bin/sh
# Lift the SPURS job binaries captured in spu_miss/ and write spu/spu_jobs.c.
#
# The title hands its job chains raw code+data blobs loaded at LS 0 -- not
# ELFs, so extract_spu_images.py cannot see them. Capture them from a run:
#
#   mkdir -p spu_miss && SPU_DUMP_MISS=spu_miss tools/boot.sh out/boot.log 60
#
# then run this and rebuild. Same recipe as sp00nznet/tornado's relift.sh.
set -e
here=$(cd "$(dirname "$0")/.." && pwd)
PS3RECOMP="${PS3RECOMP:-$here/../ps3recomp}"
PY="${PY:-$here/../.venv/bin/python}"
cd "$here"

OUT=spu/spu_jobs.c
IMG=16      # image ids 1.. belong to spu_workloads.c
{
  echo "/* GENERATED by tools/lift_spu_jobs.sh: the lifted SPURS job binaries. */"
  echo "#include \"spu_workload.h\""
  echo "extern void spu_begin_image(int image_id);"
} > "$OUT.tmp"
REG=""
for J in spu_miss/spujob_*.bin; do
    [ -f "$J" ] || continue
    FP=$(basename "$J" .bin | cut -d_ -f2)
    P="job_${FP}_"
    "$PY" "$PS3RECOMP/tools/find_spu_functions.py" "$J" --raw --base 0 \
        --out "spu_miss/job_${FP}_funcs.json"
    rm -rf "spu/job_$FP" && mkdir -p "spu/job_$FP"
    "$PY" "$PS3RECOMP/tools/spu_lifter.py" "$J" --base 0 \
        --functions "spu_miss/job_${FP}_funcs.json" \
        --symbol-prefix "$P" -o "spu/job_$FP"
    # The lifter writes includes relative to the toolkit tree; the build finds
    # the SPU headers through an include directory instead.
    sed -i '' -E 's|#include "(\.\./)+runtime/spu/|#include "|' \
        "spu/job_$FP/spu_recomp.c" "spu/job_$FP/spu_recomp.h"
    echo "extern void ${P}spu_func_00000000(spu_context*); extern void ${P}spu_recomp_register(void);" >> "$OUT.tmp"
    REG="$REG    spu_begin_image($IMG); ${P}spu_recomp_register();
    spu_workload_register_img(0x${FP}ULL, ${P}spu_func_00000000, $IMG, \"job_$FP\");
"
    IMG=$((IMG + 1))
done
{
  echo "__attribute__((constructor)) static void infamous2_spu_jobs_register(void)"
  echo "{"
  printf "%s" "$REG"
  echo "    spu_begin_image(0);"
  echo "}"
} >> "$OUT.tmp"
mv "$OUT.tmp" "$OUT"
echo "wrote $OUT"
